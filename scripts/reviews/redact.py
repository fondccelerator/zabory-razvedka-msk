NAMES='''Александр Алексей Анатолий Андрей Антон Аркадий Артем Артём Артур Богдан Борис Вадим Валентин Валерий Василий Вениамин Виктор Виталий Владимир Владислав Всеволод Вячеслав Геннадий Георгий Герман Глеб Григорий Давид Даниил Данила Денис Дмитрий Евгений Егор Иван Игорь Илья Кирилл Константин Лев Леонид Максим Марат Марк Матвей Михаил Никита Николай Олег Павел Петр Пётр Роман Ростислав Руслан Семен Семён Сергей Смаил Станислав Степан Тимофей Тимур Федор Фёдор Филипп Эдуард Юрий Ярослав Влад Влада Марина Дильшот Исмаил Андриан Виталик Рамиль Смайл Дамир Рустам Ринат Азат Ильдар Расул Шамиль Арсений Эльдар Захар Савелий Алишер Фарход Азамат Арсен Самвел Ашот Гарик Юра Толя Гена Валера Саша Дима Миша Женя Вова Коля Серега Серёжа Паша Слава Витя Леша Лёша
Александра Алена Алёна Алина Алла Анастасия Ангелина Анна Антонина Валентина Валерия Варвара Вера Вероника Виктория Галина Дарья Диана Ева Евгения Екатерина Елена Елизавета Жанна Зоя Инна Ирина Карина Кира Кристина Ксения Лариса Лидия Любовь Людмила Маргарита Марина Мария Надежда Наталья Наталия Нина Оксана Олеся Ольга Полина Раиса Светлана София Софья Тамара Татьяна Ульяна Юлия Яна Маша Даша Катя Настя Таня Света Оля Лена Наташа'''.split()
def forms(n):
    f={n}
    if n.endswith('ия'): b=n[:-1]; f|={b+'и',b+'ю',b+'ей'}
    elif n.endswith('я'): b=n[:-1]; f|={b+'и',b+'ю',b+'ей',b+'е'}
    elif n.endswith('а'): b=n[:-1]; f|={b+'ы',b+'и',b+'е',b+'у',b+'ой'}
    elif n.endswith('й'): b=n[:-1]; f|={b+'я',b+'ю',b+'ем',b+'е'}
    elif n.endswith('ь'): b=n[:-1]; f|={b+'я',b+'ю',b+'ем',b+'е'}
    else: f|={n+'а',n+'у',n+'ом',n+'е'}
    return f
ALL=set()
for n in NAMES: ALL|=forms(n)
NAME_RX=re.compile(r'\b(' + '|'.join(sorted(ALL,key=len,reverse=True)) + r')\b')
AMBIG={'вера','надежда','любовь','роман','слава','лев','марк','ева','роза','лилия'}
LOW=set(x.lower() for x in ALL)-{f for a in AMBIG for f in forms(a.capitalize())}-set(x.lower() for a in AMBIG for x in forms(a.capitalize()))
LOW_RX=re.compile(r'\b(' + '|'.join(sorted(LOW,key=len,reverse=True)) + r')\b')
BEFORE=re.compile(r'(?<=[а-яё,] )(?!Мастеровит|Заборкин|Заборово|Заборофф|Радуг|Облзабор|Москв|Слава)[А-ЯЁ][а-яё]{2,}(?= \[имя\])')
AFTER_INIT=re.compile(r'(?<=\[имя\]) [А-ЯЁ]\.')
FIO=re.compile(r'(?<!ИП )\b[А-ЯЁ][а-яё]{2,}(ов|ев|ин|ын|ский|цкий|ская|цкая|ова|ева|ина|ына|ко|ук|юк|ич|енко)\b\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.?')
FIO2=re.compile(r'\b[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?[А-ЯЁ][а-яё]{2,}')
SURN=re.compile(r'(?<!ИП )(?<=\[имя\] )[А-ЯЁ][а-яё]{2,}(ов|ев|ин|ын|ский|цкий|ская|цкая|ова|ева|ина|ына|ко|ук|юк|ич|енко|ик)\b')
PHONE=re.compile(r'(\+7|8)[\s\-\(]*\d{3}[\s\-\)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}|\b\d{3}[\s\-]\d{2}[\s\-]\d{2}\b|оканчивается на цифры [\d\- ]+')
PLATE=re.compile(r'\b[авекмнорстух]\d{3}[авекмнорстух]{0,2}\b',re.I)
EXTRA=re.compile(r'\b(Русинков\w*|Зечевич\w*|Морозов\w*|Кайдалов\w*|Долматов\w*|Четверик\w*|Петухов\w*|Бурмистров\w*|Ефремов\w*|Акулов\w*|Бутько|Кожин\w*|Новиков\w*|Прохоров\w*|Кострова|Гачава|Гаращенко|Поляквинск\w*|Шатилов\w*|Бивол\w*|Лебёдкин\w*|Кротов\w*)\b')
PATR=re.compile(r'\b[А-ЯЁ][а-яё]+(?:вич|вна|вичу|вне|вича|вны|вичем|вной|ична|ичну|ичной)\b')
DOC=re.compile(r'(?i)\b((?:договор|дог\.|заказ|заявк|обращени|претензи|счет|счёт|счет-оферт|рекламаци)[а-яё\-]*\.?\s*(?:№|N|#|номер)?\s*)([A-ZА-ЯЁ]{0,5}\s?\d[\w/\-|.]*\d|\d+)')
DOCNUM=re.compile(r'(?:№\s*|\b)\d{1,4}\s?[/|]\s?[A-Za-zА-ЯЁа-яё]{0,5}\d{0,3}[A-Za-zА-ЯЁа-яё]{0,3}(?:[\-–]\d{1,4})?\b|\bZZMS\d+\b|№\s*\d+')
def redact(t):
    if not t: return t
    t=DOC.sub(lambda m:m.group(1)+'[номер]',t)
    t=DOCNUM.sub('[номер]',t)
    t=PATR.sub('[отчество]',t)
    t=EXTRA.sub('[фамилия]',t)
    t=PHONE.sub('[телефон]',t)
    t=FIO.sub('[ФИО]',t); t=FIO2.sub('[ФИО]',t)
    t=NAME_RX.sub('[имя]',t)
    t=LOW_RX.sub('[имя]',t)
    t=SURN.sub('[фамилия]',t)
    t=BEFORE.sub('[фамилия]',t)
    t=AFTER_INIT.sub('',t)
    t=PLATE.sub('[номер]',t)
    return t
